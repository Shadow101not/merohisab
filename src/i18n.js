export const DEFAULT_LANG = 'ne';

export function makeT(lang) {
  const pick = (key) => {
    const entry = STR[key];
    if (!entry) return key;
    return lang === 'ne' ? entry[0] : entry[1];
  };
  pick.en = (key) => {
    const entry = STR[key];
    return entry ? entry[1] : key;
  };
  return pick;
}

/** replaces {{name}} placeholders */
export function fill(text, vars = {}) {
  return String(text).replace(/\{\{(\w+)\}\}/g, (m, k) =>
    vars[k] === undefined ? m : String(vars[k])
  );
}
